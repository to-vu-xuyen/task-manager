<?php

namespace backend\controllers;

use common\models\LoginForm;
use Yii;
use yii\filters\VerbFilter;
use yii\filters\AccessControl;
use yii\web\Controller;
use yii\web\Response;
use common\models\User;
use common\forms\user\UserCreateForm;
// NEW: Updated to new namespace
use common\services\user\UserService;


/**
 * Site controller
 */
class SiteController extends Controller
{
    /**
     * {@inheritdoc}
     */
    public function behaviors()
    {
        return [
            'access' => [
                'class' => AccessControl::class,
                'rules' => [
                    [
                        'actions' => ['login', 'first-time', 'error'],
                        'allow' => true,
                    ],
                    [
                        'actions' => ['logout', 'index'],
                        'allow' => true,
                        'roles' => ['@'],
                    ],
                ],
            ],
            'verbs' => [
                'class' => VerbFilter::class,
                'actions' => [
                    'logout' => ['post'],
                ],
            ],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function actions()
    {
        return [
            'error' => [
                'class' => \yii\web\ErrorAction::class,
            ],
        ];
    }

    /**
     * Displays homepage.
     *
     * @return string
     */
    public function actionIndex()
    {
        return $this->render('index');
    }

    /**
     * Login action.
     *
     * @return string|Response
     */
    public function actionLogin()
    {
        if (!Yii::$app->user->isGuest) {
            return $this->goHome();
        }

        if(empty(Yii::$app->authManager->getUserIdsByRole('admin'))){
            return $this->redirect(['site/first-time']);
        }

        $this->layout = 'blank';

        $model = new LoginForm();
        if ($model->load(Yii::$app->request->post()) && $model->login()) {
            return $this->goBack();
        }

        $model->password = '';

        return $this->render('login', [
            'model' => $model,
        ]);
    }

    /**
     * Logout action.
     *
     * @return Response
     */
    public function actionLogout()
    {
        Yii::$app->user->logout();

        return $this->goHome();
    }


    public function actionFirstTime(){
        $form = new UserCreateForm();
        $form->username = 'admin';
        $form->role = 'admin'; // Set role cho admin đầu tiên


        if($form->load(Yii::$app->request->post()) && $form->validate()){
            // NEW: Sử dụng UserService facade
            $userService = new UserService();
            $user = $userService->createUser($form, 'admin');
            
            if ($user) {
                Yii::$app->user->login($user);
                return $this->redirect(['site/index']);
            }
        }

        return $this->render('first-time',[
            'model' => $form,
        ]);
    }

}
